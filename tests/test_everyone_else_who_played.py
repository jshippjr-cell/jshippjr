"""The release clause 6A obliged composers to collect, which did not exist.

The Composer Agreement tells a writer to get a signed release from anyone who performed,
sang, programmed, produced, engineered or co-wrote — *"paid or unpaid, stranger or
friend, in the room or over the internet"*. A council review then grepped for that
release and found **zero matches outside the agreement text**. The studio was asking
composers to collect a document nobody had written, which is worse than not asking: it
reads as diligence and delivers none.

This is the gap most likely to actually void a Clearance Certificate, and it needs no bad
faith. `delivery._contributors` builds the certificate's chain of title from ASSIGNMENTS
— operator records — so a violinist the composer booked for two hours is invisible to it.
In the UK it is sharper still: performers' rights under CDPA 1988 Part II are a separate
property right the composer cannot assign on the performer's behalf.
"""
import importlib

import pytest

from chordential_oia import contributor_release
from chordential_oia.signing import DOC_CONTRIBUTOR_RELEASE, document_digest

pytest.importorskip("fastapi")


# ── the document ─────────────────────────────────────────────────────────────────────
def _rel(**kw):
    base = dict(contributor="Ana Ruiz", role="Vocalist",
                work="Winter appeal film — topline", booked_by="Dale Malleh")
    base.update(kw)
    return contributor_release.build_release(**base)


def test_it_assigns_the_performance_and_the_recording():
    text = _rel().signable_text()
    assert "You assign to Chordential" in text
    assert "full term of copyright and throughout the world" in text
    assert "all rights in your performance and in the recording of it" in text


def test_it_warrants_the_performance_is_human_and_uncopied():
    """The two things that make the certificate's claim true, asked of the person who
    actually knows."""
    text = _rel().signable_text()
    assert "performed by you, a human being" in text
    assert "not generated by an artificial-intelligence music system" in text
    assert "did not use, quote or sample anyone else's recording" in text
    assert "telling us is never a problem" in text, (
        "disclosure must be the easy path or nobody discloses")


def test_it_waives_moral_rights_and_covers_union():
    text = _rel().signable_text()
    assert "waive your moral rights" in text
    assert "AFM" in text and "SAG-AFTRA" in text
    assert "no scale, pension, health" in text


def test_a_co_writer_gets_the_composition_clause_and_a_performer_does_not():
    """A co-writer contributes to the WORK, not only the recording — and is told, in the
    document, to raise a writer share now rather than after delivery."""
    writer = _rel(role="Co-writer").signable_text()
    player = _rel(role="Performer").signable_text()
    assert "the writing, not only the performance" in writer
    assert "credited as a writer with a share" in writer
    assert "the writing, not only the performance" not in player


def test_it_is_explicitly_not_about_their_fee():
    """A session player asked to sign something by a studio they have never heard of
    assumes it is about money. It is not, and saying so is what makes it signable."""
    text = _rel().signable_text()
    assert "not about your fee" in text
    assert "between you and the person who booked you" in text


def test_it_is_short_enough_to_actually_read():
    """Four pages on a phone between takes is signed without reading, and a release
    signed without reading is the one a dispute unpicks first."""
    assert len(_rel().signable_text().splitlines()) < 45


def test_it_is_deterministic_and_shares_the_studios_jurisdiction():
    a, b = _rel().signable_text(), _rel().signable_text()
    assert a == b and document_digest(a) == document_digest(b)
    from chordential_oia import composer_agreement
    assert composer_agreement.governing_law() in a, (
        "two documents governed by different states is a fight about which one applies")


# ── the flow: the composer names them, they sign, the certificate knows ──────────────
@pytest.fixture()
def gated(tmp_path, monkeypatch):
    monkeypatch.setenv("CHORDENTIAL_DB", str(tmp_path / "contrib.db"))
    monkeypatch.setenv("CHORDENTIAL_ADMIN_TOKEN", "passphrase")
    for m in ("db", "campaigns", "app"):
        importlib.reload(importlib.import_module(f"chordential_oia.web.{m}"))
    from fastapi.testclient import TestClient
    from chordential_oia.web import app as app_mod
    with TestClient(app_mod.app) as c:
        yield c, app_mod


def _project_and_composer(app_mod):
    from chordential_oia.models import MusicDiscipline
    from chordential_oia.talent import Talent
    db = app_mod.db
    conn = db.connect()
    try:
        pid = conn.execute(
            "SELECT id FROM projects ORDER BY id LIMIT 1").fetchone()["id"]
        tid = db.insert_talent(conn, Talent(name="Dale Malleh", email="dale@example.com",
                                            disciplines=[MusicDiscipline.COMPOSITION]))
        return pid, tid, db.ensure_talent_portal_token(conn, tid)
    finally:
        conn.close()


def _name_one(c, token, pid, name="Ana Ruiz", role="Vocalist",
              email="ana@example.com"):
    return c.post(f"/creator/{token}/project/{pid}/contributor",
                  data={"name": name, "role": role, "email": email},
                  follow_redirects=False)


def test_the_composer_names_them_and_they_are_emailed(gated, monkeypatch):
    from chordential_oia import mailer
    sent = []
    monkeypatch.setattr(mailer, "mail_configured", lambda: True)
    monkeypatch.setattr(mailer, "send_email",
                        lambda to, subject, body, **kw: (sent.append((to, body))
                                                         or "sent"))
    c, app_mod = gated
    pid, _tid, token = _project_and_composer(app_mod)
    r = _name_one(c, token, pid)
    assert r.status_code == 303
    assert len(sent) == 1 and sent[0][0] == "ana@example.com"
    body = sent[0][1]
    assert "/contributor/" in body, "the mail must carry their signing link"
    assert "Dale Malleh" in body, "say who named them or it reads as spam"
    assert "not your fee" in body or "does not\nchange it" in body


def test_the_contributor_signs_without_an_account(gated):
    """They are not a user of this system and never will be — the link is the whole
    credential, and the admin gate must not meet them (it met a real client once)."""
    c, app_mod = gated
    pid, _tid, token = _project_and_composer(app_mod)
    _name_one(c, token, pid)
    conn = app_mod.db.connect()
    try:
        row = app_mod.db.list_contributors(conn, pid)[0]
    finally:
        conn.close()
    page = c.get(f"/contributor/{row['token']}")
    assert page.status_code == 200
    assert "Password or passphrase" not in page.text
    assert "CONTRIBUTOR RELEASE" in page.text

    r = c.post(f"/contributor/{row['token']}/sign",
               data={"typed_name": "Ana Ruiz", "signer_email": "ana@example.com",
                     "consent": "1"}, follow_redirects=False)
    assert r.status_code == 303
    assert "/admin/login" not in r.headers.get("location", "")
    conn = app_mod.db.connect()
    try:
        sig = app_mod.db.latest_contributor_signature(
            conn, row["id"], DOC_CONTRIBUTOR_RELEASE)
    finally:
        conn.close()
    assert sig is not None and sig["typed_name"] == "Ana Ruiz"
    assert sig["digest"] == document_digest(
        contributor_release.build_release(row).signable_text())


