def test_a_signed_release_cannot_be_deleted(gated):
    """Evidence is not removed because it is inconvenient — the rule the signature table
    already follows."""
    c, app_mod = gated
    pid, _tid, token = _project_and_composer(app_mod)
    _name_one(c, token, pid)
    conn = app_mod.db.connect()
    try:
        row = app_mod.db.list_contributors(conn, pid)[0]
        assert app_mod.db.remove_contributor(conn, row["id"]) is True
    finally:
        conn.close()
    _name_one(c, token, pid, name="Sam Vale", email="sam@example.com")
    conn = app_mod.db.connect()
    try:
        row = app_mod.db.list_contributors(conn, pid)[0]
    finally:
        conn.close()
    c.post(f"/contributor/{row['token']}/sign",
           data={"typed_name": "Sam Vale", "consent": "1"}, follow_redirects=False)
    conn = app_mod.db.connect()
    try:
        assert app_mod.db.remove_contributor(conn, row["id"]) is False
        assert len(app_mod.db.list_contributors(conn, pid)) == 1
    finally:
        conn.close()


# ── the point of all of it: the certificate knows ────────────────────────────────────
def test_the_certificate_cannot_be_signed_while_a_release_is_outstanding(gated):
    """The whole reason this exists. Warranting to a buyer that nothing in the work needs
    anyone else's permission, while holding a list of people who have not given theirs,
    is the failure the chain of title is supposed to prevent."""
    from chordential_oia.web.project_routes import _delivery_view
    c, app_mod = gated
    pid, _tid, token = _project_and_composer(app_mod)
    conn = app_mod.db.connect()
    try:
        before = _delivery_view(conn, pid)
    finally:
        conn.close()
    assert before is not None and before["release_gaps"] == []
    signable_before = before["cert_signable"]
    assert signable_before is True, (
        "the certificate is not signable even before a contributor exists — this test "
        "would then pass without proving anything")

    _name_one(c, token, pid)
    conn = app_mod.db.connect()
    try:
        view = _delivery_view(conn, pid)
        row = app_mod.db.list_contributors(conn, pid)[0]
    finally:
        conn.close()
    assert [g["name"] for g in view["release_gaps"]] == ["Ana Ruiz"]
    assert view["cert_signable"] is False, (
        "the certificate is signable with an unsigned contributor on the project")

    c.post(f"/contributor/{row['token']}/sign",
           data={"typed_name": "Ana Ruiz", "consent": "1"}, follow_redirects=False)
    conn = app_mod.db.connect()
    try:
        after = _delivery_view(conn, pid)
    finally:
        conn.close()
    assert after["release_gaps"] == []
    assert after["cert_signable"] == signable_before, "signing did not unblock it"


